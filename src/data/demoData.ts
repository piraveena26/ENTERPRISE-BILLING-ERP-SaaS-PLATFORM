/**
 * Generate default permission matrix state
 */
export function generateDefaultPermissions(): PermissionMatrixState {
  const matrix: Partial<PermissionMatrixState> = {};

  for (const role of ALL_ROLES) {
    matrix[role] = {} as Record<AppModule, Record<PermissionAction, boolean>>;
    for (const mod of ALL_MODULES) {
      matrix[role]![mod] = {} as Record<PermissionAction, boolean>;
      for (const action of ALL_PERMISSIONS) {
        // Super Admin has all permissions
        if (role === 'Super Admin' || role === 'Tenant Owner') {
          matrix[role]![mod][action] = true;
        } else if (role === 'Auditor') {
          // Auditor has View, Export, Print only
          matrix[role]![mod][action] = ['View', 'Export', 'Print'].includes(action);
        } else if (role === 'Cashier') {
          matrix[role]![mod][action] = (['Payments', 'Invoices'].includes(mod) && ['View', 'Create', 'Print'].includes(action)) || action === 'View';
        } else if (role === 'Finance Manager' || role === 'Accountant') {
          // High permissions in financial modules
          if (['Accounting', 'Invoices', 'Payments', 'Reports'].includes(mod)) {
            matrix[role]![mod][action] = action !== 'Delete';
          } else {
            matrix[role]![mod][action] = ['View', 'Print', 'Export'].includes(action);
          }
        } else {
          // Default standard permissions
          matrix[role]![mod][action] = ['View', 'Create', 'Edit', 'Print'].includes(action);
        }
      }
    }
  }

  return matrix as PermissionMatrixState;
}
